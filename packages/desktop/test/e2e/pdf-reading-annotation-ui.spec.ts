import { test, expect } from '@playwright/test'
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { PDFDocument } from 'pdf-lib'
import { launchWithDoc, expectNoRendererErrors } from './helpers'

test('reading-first UI keeps ink history and cancels incomplete gestures', async() => {
  const directory = mkdtempSync(path.join(tmpdir(), 'yarktext-reading-ui-'))
  const filename = path.join(directory, 'reader.pdf')
  const doc = await PDFDocument.create()
  doc.addPage([612, 792]).drawText('Reading and annotations', { x: 50, y: 700 })
  writeFileSync(filename, await doc.save())
  const { app, page } = await launchWithDoc(filename, { suppressErrorDialog: true })
  try {
    await expect(page.locator('.pdf-reader .textLayer')).toContainText('Reading and annotations')
    await expect(page.locator('.pdf-secondary-tools')).toHaveCount(0)
    await expect(page.locator('.pdf-tool-workspace .tool-panel')).toHaveCount(0)
    const marker = page.locator('.pdf-marker-presets button').first()
    await marker.click()
    await expect(marker).toHaveAttribute('aria-pressed', 'true')
    await marker.click()
    await expect(marker).toHaveAttribute('aria-pressed', 'false')
    await expect(page.locator('.pdf-annotation-workspace')).toHaveAttribute('data-pdf-tool', 'Select')
    await expect(page.locator('.pdf-tool-workspace nav button')).toHaveCount(4)
    await expect(page.locator('.pdf-tool-workspace').getByRole('button', { name: '注释', exact: true })).toHaveCount(0)
    await expect(page.locator('.pdf-tool-workspace nav button').first().locator('svg')).toHaveCount(1)
    await page.getByRole('button', { name: '编辑 PDF', exact: true }).click()
    await page.getByRole('button', { name: '手写画笔', exact: true }).click()
    await expect(page.locator('.pdf-tool-workspace .tool-panel')).toHaveCount(0)
    await expect(page.locator('.pdf-annotation-workspace')).toHaveAttribute('data-pdf-tool', 'Ink')
    const bounds = await page.locator('.canvasWrapper').first().boundingBox()
    if (!bounds) throw new Error('Missing PDF page')
    await page.mouse.move(bounds.x + 90, bounds.y + 160)
    await page.mouse.down()
    await page.mouse.move(bounds.x + 180, bounds.y + 200, { steps: 8 })
    await page.mouse.up()
    await expect(page.locator('.pdf-draft-layer polyline')).toHaveCount(1)
    await expect(page.locator('.pdf-annotation-sidebar')).toHaveCount(0)
    await page.getByRole('button', { name: '撤销', exact: true }).click()
    await expect(page.locator('.pdf-draft-layer polyline')).toHaveCount(0)
    await page.getByRole('button', { name: '重做', exact: true }).click()
    await expect(page.locator('.pdf-draft-layer polyline')).toHaveCount(1)
    await page.getByLabel('PDF 页面', { exact: true }).focus()
    await page.keyboard.press('Control+z')
    await expect(page.locator('.pdf-draft-layer polyline')).toHaveCount(0)
    await page.keyboard.press('Control+Shift+z')
    await expect(page.locator('.pdf-draft-layer polyline')).toHaveCount(1)
    await page.mouse.move(bounds.x + 220, bounds.y + 210)
    await page.mouse.down()
    await page.mouse.move(bounds.x + 270, bounds.y + 240)
    await page.keyboard.press('Escape')
    await page.mouse.up()
    await expect(page.locator('.pdf-draft-layer polyline')).toHaveCount(1)
    await expect(page.locator('.pdf-annotation-workspace')).toHaveAttribute('data-pdf-tool', 'Select')
    const identity = await page.locator('.pdf-draft-layer').evaluate(node => { node.setAttribute('data-stability-check', 'same'); return true })
    expect(identity).toBe(true)
    await page.getByLabel('PDF 页面', { exact: true }).evaluate(node => node.dispatchEvent(new Event('scroll')))
    await page.waitForTimeout(100)
    await expect(page.locator('.pdf-draft-layer')).toHaveAttribute('data-stability-check', 'same')
    const hit = page.locator('.pdf-draft-layer polyline').first()
    await hit.click({ position: { x: 20, y: 10 }, force: true })
    await expect(page.locator('.pdf-annotation-sidebar')).toBeVisible()
    await expect(page.locator('.pdf-annotation-item.selected')).toHaveCount(1)
    await page.getByRole('textbox', { name: '批注正文', exact: true }).fill('右键批注评论')
    await page.getByRole('button', { name: '应用修改', exact: true }).click()
    await page.locator('.pdf-draft-layer polyline').first().click({ button: 'right', position: { x: 20, y: 10 }, force: true })
    const menu = page.getByRole('menu', { name: '批注操作' })
    await expect(menu).toBeVisible()
    await menu.locator('summary').click()
    await menu.getByRole('button', { name: '批注颜色 #ed4145', exact: true }).click()
    await expect(page.locator('.pdf-draft-layer g[data-annotation-id]').first()).toHaveAttribute('stroke', '#ed4145')
    await page.locator('.pdf-annotation-item.selected').click({ button: 'right' })
    await menu.getByRole('menuitem', { name: '复制评论文字', exact: true }).click()
    await expect.poll(() => app.evaluate(({ clipboard }) => clipboard.readText())).toBe('右键批注评论')
    await page.locator('.pdf-annotation-item.selected').click({ button: 'right' })
    await menu.getByRole('menuitem', { name: '复制批注', exact: true }).click()
    await expect(page.locator('.pdf-draft-layer polyline')).toHaveCount(2)
    await page.locator('.pdf-annotation-item.selected').click({ button: 'right' })
    await menu.getByRole('menuitem', { name: '删除批注', exact: true }).click()
    await expect(page.locator('.pdf-draft-layer polyline')).toHaveCount(1)
    await page.getByRole('button', { name: '保存批注', exact: true }).click()
    await expect(page.locator('.pdf-draft-layer polyline')).toHaveCount(0)
    await expect(page.locator('.pdf-reader .textLayer')).toContainText('Reading and annotations')
    await expectNoRendererErrors(app)
  } finally {
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().forEach(window => window.destroy())).catch(() => {})
    await app.close()
    rmSync(directory, { recursive: true, force: true })
  }
})
