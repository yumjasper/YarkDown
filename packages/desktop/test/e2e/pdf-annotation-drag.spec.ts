import { test, expect } from '@playwright/test'
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { PDFDocument } from 'pdf-lib'
import { launchWithDoc, expectNoRendererErrors } from './helpers'

test('annotations follow the pointer before release and movement is undoable and cancellable', async() => {
  test.setTimeout(90000)
  const directory = mkdtempSync(path.join(tmpdir(), 'yarktext-pdf-drag-'))
  const filename = path.join(directory, 'drag.pdf')
  const doc = await PDFDocument.create()
  doc.addPage([612, 792]).drawText('Annotation drag regression', { x: 50, y: 700 })
  writeFileSync(filename, await doc.save())
  const { app, page } = await launchWithDoc(filename, { suppressErrorDialog: true })
  try {
    await expect(page.locator('.pdf-reader .textLayer')).toContainText('Annotation drag regression')
    await page.getByRole('button', { name: '编辑 PDF', exact: true }).click()
    const frames = () => page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
    const canvas = page.locator('.canvasWrapper').first()
    await page.getByRole('button', { name: '文本题注', exact: true }).click()
    await frames()
    let box = await canvas.boundingBox()
    if (!box) throw new Error('Missing PDF page')
    await page.mouse.click(box.x + 100, box.y + 220)
    const group = page.locator('.pdf-draft-layer g[data-annotation-id]').first()
    await expect(group).toBeVisible()
    const handle = page.getByRole('button', { name: '移动题注', exact: true })
    await expect(handle).toBeVisible()
    await frames()
    const original = await group.locator('image').boundingBox()
    const handleBox = await handle.boundingBox()
    if (!original || !handleBox) throw new Error('Missing caption controls')
    await page.mouse.move(handleBox.x + handleBox.width / 2, handleBox.y + handleBox.height / 2)
    await page.mouse.down()
    await page.mouse.move(handleBox.x + handleBox.width / 2 + 70, handleBox.y + handleBox.height / 2 + 35, { steps: 10 })
    await frames()
    const preview = await group.locator('image').boundingBox()
    expect((preview?.x ?? NaN) - original.x).toBeCloseTo(70, 0)
    expect((preview?.y ?? NaN) - original.y).toBeCloseTo(35, 0)
    await expect(group).toHaveAttribute('transform', /translate\(/)
    await page.mouse.up()
    await expect(group).not.toHaveAttribute('transform', /translate\(/)
    const committed = await group.locator('image').boundingBox()
    expect((committed?.x ?? NaN) - original.x).toBeCloseTo(70, 0)
    await page.getByRole('button', { name: '撤销', exact: true }).click()
    await frames()
    expect((await group.locator('image').boundingBox())?.x).toBeCloseTo(original.x, 0)

    for (const kind of ['便签评论', '矩形']) {
      await page.getByRole('button', { name: kind, exact: true }).click()
      await frames()
      box = await canvas.boundingBox()
      if (!box) throw new Error('Missing PDF page')
      await page.mouse.move(box.x + 100, box.y + 330)
      await page.mouse.down()
      if (kind === '矩形') await page.mouse.move(box.x + 180, box.y + 370, { steps: 5 })
      await page.mouse.up()
      await page.getByRole('button', { name: '选择', exact: true }).click()
      const target = page.locator('.pdf-draft-layer g[data-annotation-id]').last()
      await expect(target).toBeVisible()
      await target.click({ position: { x: 5, y: 5 }, force: true })
      await frames()
      const before = await target.locator(':scope > :first-child').boundingBox()
      if (!before) throw new Error('Missing annotation')
      await page.mouse.move(before.x + 5, before.y + 5)
      await page.mouse.down()
      await page.mouse.move(before.x + 45, before.y + 30, { steps: 8 })
      await frames()
      await expect(target).toHaveAttribute('transform', /translate\(/)
      expect(((await target.locator(':scope > :first-child').boundingBox())?.x ?? NaN) - before.x).toBeCloseTo(40, 0)
      await page.keyboard.press('Escape')
      await page.mouse.up()
      await frames()
      await expect(target).not.toHaveAttribute('transform', /translate\(/)
      expect(((await target.locator(':scope > :first-child').boundingBox())?.x ?? NaN)).toBeCloseTo(before.x, 0)
    }
    await expectNoRendererErrors(app)
  } finally {
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().forEach(window => window.destroy())).catch(() => {})
    await app.close()
    rmSync(directory, { recursive: true, force: true })
  }
})
