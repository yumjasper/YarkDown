import { expect, test } from '@playwright/test'
import { expectNoRendererErrors, launchElectron } from './helpers'

test('stable button edges, toggle menus and rounded preferences in light and dark themes', async() => {
  test.setTimeout(90000)
  const { app, page } = await launchElectron([], { suppressErrorDialog: true, preferences: { startUpAction: 'blank', theme: 'light' } })
  try {
    const home = page.getByTestId('home-new-file')
    await expect(home).toBeVisible()
    const buttons = page.locator('.home-actions .el-button')
    for (let i = 0; i < await buttons.count(); i++) {
      const button = buttons.nth(i)
      const initial = await button.boundingBox()
      if (!initial) throw new Error('Missing home button')
      for (const offset of [-.5, .5, -.5]) {
        await page.mouse.move(initial.x + initial.width + offset, initial.y + initial.height / 2)
        await expect.poll(async() => (await button.boundingBox())?.width).toBe(initial.width)
      }
      await button.focus()
      expect((await button.boundingBox())?.width).toBe(initial.width)
      expect(await button.evaluate(el => getComputedStyle(el).transitionProperty)).not.toContain('all')
    }
    await page.screenshot({ path: '../../.tools/ui-home-refined.png' })
    await home.click()
    const paragraph = page.locator('.bottom-toolbar-button[data-id="paragraph"]')
    await paragraph.click()
    await expect(paragraph).toHaveAttribute('aria-expanded', 'true')
    await paragraph.click()
    await expect(paragraph).toHaveAttribute('aria-expanded', 'false')
    const file = page.locator('.menu-bar-item').filter({ hasText: /^文件$/ })
    for (let count = 0; count < 4; count++) {
      await file.click()
      await expect(page.locator('.app-top-menu-panel')).toHaveCount(count % 2 ? 0 : 1)
    }
    await file.click()
    await page.locator('.menu-bar-item').filter({ hasText: /^编辑$/ }).hover()
    await expect(file).toHaveAttribute('aria-expanded', 'false')
    await expect(page.locator('.menu-bar-item').filter({ hasText: /^编辑$/ })).toHaveAttribute('aria-expanded', 'true')
    await page.screenshot({ path: '../../.tools/ui-menu-refined.png' })
    await page.locator('.editor-component').click({ position: { x: 600, y: 220 } })
    await expect(page.locator('.app-top-menu-panel')).toHaveCount(0)
    await file.focus(); await page.keyboard.press('ArrowDown')
    await expect(page.locator('.app-top-menu-panel')).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(file).toBeFocused()
    await file.click()
    const panel = page.locator('.app-top-menu-panel')
    const before = await page.locator('.tabs-container li').count()
    await panel.getByRole('menuitem', { name: /新建标签|新建文件/ }).first().click()
    await expect(page.locator('.tabs-container li')).toHaveCount(before + 1)
    await file.click()
    const autosave = panel.getByRole('menuitemcheckbox', { name: /自动保存/ })
    const checked = await autosave.getAttribute('aria-checked')
    await autosave.click()
    await file.click()
    await expect(autosave).toHaveAttribute('aria-checked', checked === 'true' ? 'false' : 'true')
    await autosave.click()
    await page.locator('.menu-bar-item').filter({ hasText: /^编辑$/ }).click()
    await panel.getByRole('menuitem', { name: /行结束符/ }).hover()
    const endings = page.locator('.app-menu-child')
    await expect(endings).toBeVisible()
    await endings.getByRole('menuitemradio').first().click()
    await expect(page.locator('.app-top-menu-panel, .app-menu-child')).toHaveCount(0)
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.send('mt::new-untitled-tab', true, 'Plain text', true))
    await expect(page.locator('.plain-text-workspace')).toBeVisible()
    await page.locator('.app-menu-bar button').filter({ hasText: /^查找$/ }).click()
    await expect(page.locator('.search-bar')).toBeVisible()
    await expect(page.locator('.app-top-menu-panel')).toHaveCount(0)
    await page.keyboard.press('Escape')
    const settingsPromise = app.waitForEvent('window')
    await app.evaluate(({ ipcMain }) => ipcMain.emit('app-create-settings-window'))
    const settings = await settingsPromise
    await expect(settings.locator('.pref-general')).toBeVisible()
    const switchControl = settings.locator('.pref-switch-item .el-switch').first()
    const initialState = (await switchControl.getAttribute('class'))?.includes('is-checked')
    await switchControl.click()
    if (initialState) await expect(switchControl).not.toHaveClass(/is-checked/)
    else await expect(switchControl).toHaveClass(/is-checked/)
    await switchControl.click()
    const geometry = await settings.evaluate(() => {
      const root = document.querySelector('.pref-setting') as HTMLElement
      const card = document.querySelector('.pref-compound-body') as HTMLElement
      const thumb = getComputedStyle(root, '::-webkit-scrollbar-thumb')
      return { overflow: root.scrollWidth > root.clientWidth, radius: getComputedStyle(card).borderRadius, thumb: thumb.borderRadius }
    })
    expect(geometry).toEqual({ overflow: false, radius: '12px', thumb: '999px' })
    await settings.screenshot({ path: '../../.tools/ui-preferences-light.png' })
    await settings.locator('.pref-sidebar .category .item').filter({ hasText: /^主题$/ }).click()
    await expect(settings.locator('.pref-theme')).toBeVisible()
    await settings.locator('.theme.dark').click()
    await expect.poll(() => settings.locator('.pref-container').evaluate(el => getComputedStyle(el).getPropertyValue('--editorBgColor'))).not.toContain('255, 255, 255')
    await settings.locator('.pref-sidebar .category .item').first().click()
    await settings.screenshot({ path: '../../.tools/ui-preferences-dark.png' })
    await settings.getByRole('button', { name: '返回应用' }).click()
    await expectNoRendererErrors(app)
  } finally {
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().forEach(win => win.destroy()))
    await app.close()
  }
})
